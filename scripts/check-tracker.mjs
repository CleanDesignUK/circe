import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";

const context = vm.createContext({document:{addEventListener(){}}});
for (const file of ["foods.js", "food-expansion.js","engine.js","products.js","recipes.js","goals.js"]) vm.runInContext(readFileSync(new URL("../public/" + file, import.meta.url), "utf8"), context);
const engine = vm.runInContext("Engine", context), foods = context.CIRCE_FOODS;
const parse = text => engine.parse(text, foods);
const example = parse(engine.EXAMPLE);
assert.equal(example.length, 6);
assert.deepEqual(Array.from(example, r => r.food.image), ["eggs", "bread", "rice", "monster", "heineken", "cola"]);
assert.equal(example.reduce((sum, r) => sum + r.qty * r.food.kcal, 0), 1318);
assert.equal(parse("telur rebus dua")[0].qty, 2);
assert.equal(parse("100 g boiled egg")[0].qty, 2);
assert.equal(parse("1/2 boiled egg")[0].qty, 0.5);
assert.equal(parse("500 ml Coke Zero")[0].qty, 1.515);
assert.equal(parse("2 x 250 ml Coca-Cola")[0].qty, 1.515);
assert.equal(parse("Monster Ultra")[0].food.kcal < parse("Monster drink")[0].food.kcal, true);
assert.equal(parse("Tesco mystery pasta")[0].food, null);
assert.equal(parse("unrecognised meal")[0].food, null);
assert.equal(engine.target({ weight:70, height:170, age:30, sex:"female", activity:1.375, goal:0 }), 1996);
assert.equal(engine.target({ custom:2000 }), 2000);
assert.equal(engine.activeKcal(5,30,80),160);
assert.equal(engine.activeKcal(5,30,null),null);
assert.equal(engine.offset("2028-02-28",1),"2028-02-29");
console.log("Verified mixed meal, English and Indonesian aliases, brand variants, quantities, targets, workouts and dates.");

const products=vm.runInContext("Products",context), recipes=vm.runInContext("Recipes",context);
const catalogue=JSON.parse(readFileSync(new URL("../public/packaged-index.json",import.meta.url),"utf8"));
products.init(catalogue.rows);
const mixed=parse("5 pieces of Solaria wonton without sauce, 150g capcai Solaria, matcha (150ml Arummi less fat milk, pure matcha Matchamu)");
assert.equal(mixed.length,3);
assert.equal(mixed[0].qty,5);
assert.equal(mixed[0].methodQuestion,true);
assert.equal(parse("5 Solaria fried wontons")[0].food.kcal*5,280);
assert.equal(Math.round(mixed[1].qty*mixed[1].food.kcal),101);
assert.equal(mixed[2].food.recipe.length,2);
assert.equal(Math.round(mixed[2].food.kcal),81);
assert.equal(mixed[2].food.recipe[0].brand,"Arummi");
const ingredients=recipes.components("120 g chicken, 150 g rice, 80 g vegetables",foods);
const boil=recipes.make("Lunch",ingredients,"Boiled / steamed",0,1),fried=recipes.make("Lunch",ingredients,"Pan / stir fried",1,1);
assert(boil.kcal>350);assert.equal(fried.kcal-boil.kcal,40);
assert.equal(recipes.make("Lunch",recipes.components("mystery ingredient",foods),"Grilled",0,1),null);
assert.equal(products.auto(catalogue.rows[0][0]).code,catalogue.rows[0][0]);
assert.equal(vm.runInContext("weightStats({startWeight:90,weight:85,goalWeight:80}).progress",context),50);
assert.equal(vm.runInContext("weightStats({startWeight:60,weight:64,goalWeight:65}).remaining",context),1);
console.log("Verified grouped drinks, portion mass, cooking questions, ingredient estimates, indexed products and goal weights.");
